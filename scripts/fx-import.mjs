// Imports graf/assety-m1.md (JSON blocks, schema graf-fx/1) into src/data/fx-m1.ts.
// Every hex colour is replaced by a PALETTE key from src/data/style.ts; an unknown hex aborts.
// Usage (from prog/game): node scripts/fx-import.mjs [path/to/assety-m1.md]   (LUZ / Pracownik 4)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, process.argv[2] ?? '../../graf/assety-m1.md');
const out = resolve(root, 'src/data/fx-m1.ts');

// Canonical hex → PaletteKey. Hexes shared by several roles get the combat/default role here;
// CONTEXT overrides pick the base/energy role (same colour on screen).
const HEX = {
  '#0B0F14': 'background', '#3B4552': 'floor', '#8B98A5': 'wall', '#6B7280': 'rubble',
  '#7D7A4F': 'vegetation', '#56606B': 'rails', '#9A7BFF': 'hazardLiquid', '#FFFFFF': 'player',
  '#1F3B57': 'playerHalo', '#FF5FC8': 'enemy', '#BDEBFF': 'playerShot', '#FFE14D': 'warning',
  '#3DDC97': 'safe', '#0F3326': 'evacBg', '#C9D1D9': 'text', '#2A2F36': 'descentBg',
  '#B08850': 'chest', '#56B4E9': 'rarity2', '#0E2A3F': 'rarity2Bg', '#FFB000': 'rarity3',
  '#3A2A00': 'rarity3Bg', '#4A1240': 'telegraphBg', '#3D0F2E': 'bossBg', '#3A3410': 'dataCoreBg',
  '#2A323C': 'sectorOff', '#5A6573': 'floorHighContrast',
};
// Document palette names (fx_common.palette) → PaletteKey.
const DOC_NAMES = {
  tracks: 'rails', liquid: 'hazardLiquid', safeCellBg: 'evacBg', descentCellBg: 'descentBg',
  crate: 'chest', rarity2CellBg: 'rarity2Bg', rarity3CellBg: 'rarity3Bg',
  telegraphTargetBg: 'telegraphBg', bossCellBg: 'bossBg', dataCoreCellBg: 'dataCoreBg',
  sectorDark: 'sectorOff',
};
const COLOR_KEYS = new Set(['fg', 'bg', 'litFg', 'outline', 'color']);

function key(hex, ctx) {
  const h = hex.toUpperCase();
  if (h === '#FFE14D' && /^(fx_base_|screen_base)/.test(ctx.id)) return 'energy';
  if (h === '#C9D1D9' && ctx.ch === '>') return 'descent';
  const k = HEX[h];
  if (!k) throw new Error(`${ctx.id}: unknown colour ${hex}`);
  return k;
}

function convert(v, ctx) {
  if (Array.isArray(v)) return v.map((x) => convert(x, ctx));
  if (!v || typeof v !== 'object') return v;
  const o = {};
  const c = { ...ctx, ch: typeof v.ch === 'string' ? v.ch : ctx.ch };
  for (const [k, x] of Object.entries(v)) {
    if (COLOR_KEYS.has(k) && typeof x === 'string' && /^#[0-9a-f]{6}$/i.test(x)) o[k] = key(x, c);
    else o[k] = convert(x, c);
  }
  return o;
}

const md = readFileSync(src, 'utf8');
const version = /\*\*Wersja\*\*\s*\|\s*([^|\n]+)/.exec(md)?.[1].trim() ?? '?';
const blocks = [...md.matchAll(/```json\n([\s\S]*?)```/g)].map((m) => JSON.parse(m[1]));
const byId = new Map(blocks.map((b) => [b.id, b]));
const common = byId.get('fx_common');
common.palette = Object.fromEntries(
  Object.entries(common.palette).map(([n, hex]) => {
    const k = DOC_NAMES[n] ?? n;
    if (HEX[hex.toUpperCase()] !== k && !(k === 'energy' && hex.toUpperCase() === '#FFE14D') &&
        !(['descent', 'rarity1'].includes(k) && hex.toUpperCase() === '#C9D1D9'))
      throw new Error(`palette ${n} ${hex} ≠ ${k}`);
    return [n, k];
  }),
);
const special = new Set(['fx_common', 'glyphs_m1', 'screen_base_m1']);
const effects = blocks.filter((b) => !special.has(b.id)).map((b) => convert(b, { id: b.id }));
const j = (v) => JSON.stringify(v, null, 2);

writeFileSync(
  out,
  `// GENERATED by scripts/fx-import.mjs from graf/assety-m1.md ${version} – DO NOT EDIT BY HAND.
// ${blocks.length} JSON blocks: ${effects.length} effects + fx_common + glyphs_m1 + screen_base_m1.
// Colours are PaletteKeys (src/data/style.ts). Format and types: src/data/fx.ts.
import type { FxCommon, FxDef } from './fx';

export const FX_COMMON_DATA = ${j(common)} satisfies FxCommon;

export const FX_GLYPHS_M1_DATA = ${j(convert(byId.get('glyphs_m1'), { id: 'glyphs_m1' }))};

export const SCREEN_BASE_M1_DATA = ${j(convert(byId.get('screen_base_m1'), { id: 'screen_base_m1' }))};

export const FX_M1_DATA = {
${effects.map((e) => `  ${e.id}: ${j(e).replace(/\n/g, '\n  ')},`).join('\n')}
} satisfies Record<string, FxDef>;
`,
);
console.log(`fx-m1.ts: ${effects.length} effects (+3 data blocks) from ${src} ${version}`);
